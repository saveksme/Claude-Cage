import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createWorkbench } from './workbench-fixture.mjs';
const output = fileURLToPath(new URL('../../.oil-ui/local-account/shots/', import.meta.url));
await fs.mkdir(output, { recursive: true });
let launchAcks = 0;
const {browser,page,state,errors} = await createWorkbench({nativeRequest: async ({action}) => {
  if (action === 'workbenchReady') { launchAcks++; return true; }
  return null;
}});
await page.exposeFunction('fixtureLaunchAcks', () => launchAcks);
const accountMenu = () => page.getByRole('button', { name: /Меню аккаунта,/ });
async function checkMenuLayout() {
  const trigger = accountMenu();
  const settings = page.getByRole('button', { name: 'Настройки', exact: true });
  const list = page.getByRole('menu', { name: 'Меню локального аккаунта' });
  const projects = page.locator('.sidebar-scroll');
  const before = await Promise.all([trigger.boundingBox(), settings.boundingBox(), projects.boundingBox()]);
  await trigger.click();
  const menu = await list.boundingBox();
  assert.ok(menu.y >= 0 && menu.y + menu.height <= before[0].y);
  assert.deepEqual(await trigger.boundingBox(), before[0]);
  assert.deepEqual(await settings.boundingBox(), before[1]);
  const projectBox = await projects.boundingBox();
  assert.ok(projectBox.y + projectBox.height <= menu.y);
  assert.equal(await page.getByRole('menuitem', {name:'Настройки',exact:true}).evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('ArrowDown');
  assert.equal(await page.getByRole('menuitem', {name:/Заблокировать Cage/}).evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('Escape');
  await list.waitFor({state:'hidden'});
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
  assert.deepEqual(await projects.boundingBox(), before[2]);
}
try {
  Object.assign(state.account, {exists:false,unlocked:false,username:''});
  const previousAcks = launchAcks;
  await page.reload();
  await page.getByRole('heading',{name:'Регистрация аккаунта Cage'}).waitFor();
  await page.waitForFunction(async (previous) => await window.fixtureLaunchAcks() > previous, previousAcks);
  await page.screenshot({path:output+'create.png'});
  await page.getByLabel('Имя пользователя',{exact:true}).fill('林间工作室');
  await page.getByLabel('Задать пароль',{exact:true}).fill('fixture-password');
  await page.getByLabel('Подтвердите пароль',{exact:true}).fill('fixture-password');
  await page.getByRole('button',{name:'Создать локальный аккаунт',exact:true}).click();
  await accountMenu().waitFor();
  await checkMenuLayout();
  await accountMenu().press('Enter');
  await page.screenshot({path:output+'menu.png'});
  await page.keyboard.press('Enter');
  await page.getByRole('heading',{name:'Аккаунт',exact:true}).waitFor();
  const groups = page.getByRole('navigation',{name:'Разделы настроек'});
  await groups.getByRole('button',{name:'Основные',exact:true}).click();
  await page.getByRole('heading',{name:'Клавиатурные привычки',exact:true}).waitFor();
  await groups.getByRole('button',{name:'Аккаунт',exact:true}).click();
  await page.getByLabel('Имя пользователя',{exact:true}).fill('山雀的工作室');
  await page.getByLabel('Выбрать изображение аватара').setInputFiles(fileURLToPath(new URL('../src/logo.png',import.meta.url)));
  state.failAccountSave=true;
  await page.getByRole('button',{name:'Сохранить данные',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Не удалось сохранить профиль'}).waitFor();
  assert.equal(await page.getByLabel('Имя пользователя',{exact:true}).inputValue(),'山雀的工作室');
  assert.equal(state.account.username,'林间工作室');
  state.failAccountSave=false;
  await page.getByRole('button',{name:'Сохранить данные',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Данные аккаунта сохранены'}).waitFor();
  assert.equal(state.account.username,'山雀的工作室');
  assert.match(state.account.avatar,/^data:image\/png;base64,/);
  await page.screenshot({path:output+'settings.png'});
  await page.getByLabel('Текущий пароль',{exact:true}).fill('fixture-password');
  await page.getByLabel('Новый пароль',{exact:true}).fill('changed-fixture-password');
  await page.getByLabel('Подтвердите новый пароль',{exact:true}).fill('changed-fixture-password');
  await page.getByRole('button',{name:'Изменить пароль',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Пароль изменён'}).waitFor();
  await page.getByRole('button',{name:'Вернуться в рабочую среду',exact:true}).click();
  state.status.vm_running=true;state.status.ready=true;
  await page.reload();
  await page.getByRole('button',{name:/^Создать терминал в проекте /}).click();
  await page.getByRole('menuitem',{name:'Обычный терминал',exact:true}).click();
  const ids=state.terminals.map(x=>x.id);
  await accountMenu().click();
  await page.getByRole('menuitem',{name:/Заблокировать Cage/}).click();
  await page.getByRole('region',{name:'Разблокировать Cage',exact:true}).waitFor();
  assert.equal(state.status.vm_running,true);
  assert.deepEqual(state.terminals.map(x=>x.id),ids);
  await page.getByText('Фоновая среда продолжает работать, задачи не остановлены',{exact:true}).waitFor();
  await page.screenshot({path:output+'locked.png'});
  await page.getByLabel('Пароль аккаунта',{exact:true}).fill('fixture-password');
  await page.getByRole('button',{name:'Разблокировать Cage',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Неверный пароль'}).waitFor();
  await page.getByLabel('Пароль аккаунта',{exact:true}).fill('changed-fixture-password');
  await page.getByRole('button',{name:'Разблокировать Cage',exact:true}).click();
  await accountMenu().waitFor();
  assert.deepEqual(state.terminals.map(x=>x.id),ids);
  await page.reload();
  await accountMenu().waitFor();
  assert.match(await accountMenu().getAttribute('aria-label'),/山雀的工作室/);
  await accountMenu().click();
  await page.getByRole('menuitem',{name:'Настройки',exact:true}).click();
  assert.equal(await page.getByLabel('Имя пользователя',{exact:true}).inputValue(),'山雀的工作室');
  await page.setViewportSize({width:820,height:558});
  await page.screenshot({path:output+'settings-small.png'});
  await page.getByRole('button',{name:'Вернуться в рабочую среду',exact:true}).click();
  await checkMenuLayout();
  await accountMenu().click();
  await page.getByRole('menuitem',{name:'Выйти из аккаунта',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Остановить среду и выйти из аккаунта',exact:true}).click();
  await page.getByRole('region',{name:'Разблокировать Cage',exact:true}).waitFor();
  assert.equal(state.status.vm_running,false);
  assert.equal(state.terminals.length,0);
  assert.deepEqual(errors,[]);
  console.log('PASS: account creation, avatar/profile persistence, save failure, password change, lock with live terminals, unlock and stop-on-logout');
} finally {await browser.close();}
