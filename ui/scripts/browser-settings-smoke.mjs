  assert.equal(await address.inputValue(), nextHome, 'switching categories preserves unsaved address');
  fixtureState.failSave = true;
  await settings.getByRole('button', { name: 'Сохранить адрес', exact: true }).click();
  await settings.getByRole('alert').getByText('Не удалось сохранить настройки браузера; повторите попытку', { exact: true }).waitFor();
  assert.equal(await address.inputValue(), nextHome);
  fixtureState.failSave = false;
  await settings.getByRole('button', { name: 'Сохранить адрес', exact: true }).click();
  await settings.getByRole('status').getByText('Сохранено', { exact: true }).waitFor();
