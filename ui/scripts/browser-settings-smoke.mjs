  const preview = settings.getByRole('region', { name: 'Подтверждение установки расширения', exact: true });
  await preview.getByText('storage', { exact: true }).waitFor();
  await preview.getByRole('button', { name: 'Отмена', exact: true }).click();
  assert.equal((await controller.api('/extensions', { mode: 'list' })).items.length, 0);
  await file.setInputFiles({ name: 'reading-extension.zip', mimeType: 'application/zip', buffer: f.archive });
  await preview.getByRole('button', { name: 'Установить расширение', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('input[aria-label="Включить Помощник чтения"]')?.checked === true);
  checks.push('ZIP install shows permissions before confirmation; cancel installs nothing; confirming installs the real extension');
  await settings.getByRole('textbox', { name: 'Поиск по настройкам браузера', exact: true }).fill('новая вкладка');
  await address.waitFor();
  await settings.getByRole('textbox', { name: 'Поиск по настройкам браузера', exact: true }).fill('');
  await nav.getByRole('button', { name: 'Внешний вид', exact: true }).click();
  await page.setViewportSize({ width: 820, height: 558 });
  await shot('minimum-window');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
