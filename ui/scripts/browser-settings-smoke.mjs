  await importer.getByText('Помощник чтения', { exact: true }).waitFor();
  assert.equal(await importer.getByRole('checkbox').nth(1).isDisabled(), true);
  await importer.getByRole('button', { name: 'Выбрать все совместимые расширения', exact: true }).click();
