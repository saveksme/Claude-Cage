  await importer.waitFor({ state: 'hidden' });
  const enabled = settings.getByRole('checkbox', { name: 'Включить Помощник чтения', exact: true });
  assert.equal(await enabled.isChecked(), false);
  await enabled.click();
  await page.waitForFunction(() => document.querySelector('input[aria-label="Включить Помощник чтения"]')?.checked === true);
  await controller.waitFor(async () => (await controller.api('/extensions', { mode: 'list' })).items.some(item => item.enabled), 'enable imported extension');
  await settings.evaluate(element => { element.scrollTop = 0; });
  await shot('extensions-imported');
  const web = await controller.api('/new', { url: controller.origin + '/import-test' });
  await controller.waitFor(() => controller.evaluate(web.id, 'document.documentElement.dataset.cageSettingsExtension === "active"'), 'imported extension runs');
  await page.getByRole('tab', { name: 'Настройки', exact: true }).click();
  await settings.getByRole('button', { name: 'Обновить расширения', exact: true }).click();
  await settings.getByRole('button', { name: 'Удалить', exact: true }).click();
  await page.getByRole('dialog', { name: 'Удалить это расширение?', exact: true }).getByRole('button', { name: 'Удалить расширение', exact: true }).click();
  await settings.getByText('Сделайте браузер удобнее', { exact: true }).waitFor();
