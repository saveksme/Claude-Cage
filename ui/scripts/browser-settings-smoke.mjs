  await controller.waitFor(async () => (await controller.api('/tabs')).tabs.some(tab => tab.url === nextHome), 'new page uses saved address');
  await page.waitForFunction(url => document.querySelector('.address-bar input')?.value === url, nextHome);
  await page.getByRole('button', { name: 'Меню браузера', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Настройки', exact: true }).click();
  await settings.waitFor();
  assert.equal(await page.getByRole('tab', { name: 'Настройки', exact: true }).count(), 1);
  await nav.getByRole('button', { name: 'Внешний вид', exact: true }).click();
  const layout = settings.getByRole('combobox', { name: 'Макет панели вкладок', exact: true });
  await layout.click();
  await settings.getByRole('option', { name: 'Вертикально (слева)', exact: true }).click();
  await page.getByRole('complementary', { name: 'Вертикальная панель вкладок' }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: 'Открыть браузер', exact: true }).click();
  await page.getByRole('complementary', { name: 'Вертикальная панель вкладок' }).waitFor();
