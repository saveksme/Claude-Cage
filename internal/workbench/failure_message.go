func serviceHTTPFailure(action string, status int) error {
	reason, next := fmt.Sprintf("служба вернула HTTP %d, распознать конкретную причину пока не удалось", status), failureHelp
	switch status {
	case http.StatusUnauthorized, http.StatusForbidden:
		reason, next = "служба отклонила авторизацию этого подключения", "Переподключите текущую среду; если ошибка повторяется, обновите компоненты среды и повторите попытку."
	case http.StatusNotFound, http.StatusGone:
		reason, next = "целевое окно, файл или интерфейс службы больше не существуют", "Снова откройте целевое окно или выберите файл; если среда устарела, сначала обновите компоненты среды."
	case http.StatusConflict:
		reason, next = "целевое состояние изменилось или другое действие ещё не завершено", "Проверьте текущую страницу и целевой файл и запустите это действие заново."
	case http.StatusRequestEntityTooLarge:
		reason, next = "размер файла или запроса превышает допустимый для службы", "Уменьшите файл или обработайте его по частям и запустите действие заново."
	case http.StatusTooManyRequests:
		reason, next = "служба временно ограничила число запросов", "Подождите немного и повторите попытку, не нажимайте кнопку многократно."
	case http.StatusBadGateway, http.StatusServiceUnavailable:
		reason, next = "служба в среде ещё не готова или перестала отвечать", "Сначала убедитесь, что среда запущена; если подключение не восстанавливается, проверьте состояние компонентов в настройках среды."
	case http.StatusGatewayTimeout:
		reason, next = "истекло время ожидания ответа службы в среде", "Проверьте нагрузку на среду и повторите позже; если тайм-ауты продолжаются, экспортируйте диагностический пакет."
	}
	return usererror.New("действие «"+action+"»", reason, next, nil)
}

